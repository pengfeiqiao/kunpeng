#!/usr/bin/env node
/**
 * build-motion-runtime — 把 src/lib/motion/runtime/index.ts 打包成
 * scripts/motion-runtime.js（IIFE），供预览端（vite ?raw 导入）和
 * 导出端（render-worker.mjs fs 读取内联）共享同一份运行时。
 *
 * 同时：
 * 1. 断言产物不含自走时钟/随机 API（确定性防线）；
 * 2. 以产物内容 hash 作为 KP_MOTION_VERSION，写入 src/lib/motion/runtimeVersion.ts
 *    （fxRender cacheKey 用它做缓存失效）。
 */
import { build } from 'esbuild';
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const entry = path.join(root, 'src/lib/motion/runtime/index.ts');
const outFile = path.join(root, 'scripts/motion-runtime.js');
const versionFile = path.join(root, 'src/lib/motion/runtimeVersion.ts');

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: 'iife',
  target: 'chrome100',
  minify: false,
  write: false,
  legalComments: 'none',
  define: { KP_MOTION_VERSION_INJECTED: '"__KP_VERSION__"' },
});

let code = result.outputFiles[0].text;

// ── 确定性断言：禁自走时钟/随机源 ──────────────────────────────────────────────
// mulberry32（noise.ts）只在构造期从 seed 生成相位表，不属于随机源。
const banned = [
  { re: /requestAnimationFrame/, name: 'requestAnimationFrame' },
  { re: /\bsetInterval\b/, name: 'setInterval' },
  { re: /\bsetTimeout\b/, name: 'setTimeout' },
  { re: /Date\.now\s*\(/, name: 'Date.now()' },
  { re: /new\s+Date\s*\(/, name: 'new Date()' },
  { re: /Math\.random\s*\(/, name: 'Math.random()' },
  { re: /performance\.now\s*\(/, name: 'performance.now()' },
];
const violations = banned.filter((b) => b.re.test(code)).map((b) => b.name);
if (violations.length) {
  console.error(`[build-motion-runtime] 产物包含禁用 API（破坏确定性）：${violations.join(', ')}`);
  process.exit(1);
}

const hash = crypto.createHash('sha256').update(code).digest('hex').slice(0, 10);
code = code.replaceAll('__KP_VERSION__', hash);

const banner = `/* KPMotion runtime — generated by scripts/build-motion-runtime.mjs. DO NOT EDIT.\n * KP_MOTION_VERSION=${hash}\n */\n`;
await fs.writeFile(outFile, banner + code, 'utf8');
await fs.writeFile(
  versionFile,
  `/** 由 scripts/build-motion-runtime.mjs 生成，勿手改。 */\nexport const KP_MOTION_VERSION = '${hash}';\n`,
  'utf8',
);

console.log(`[build-motion-runtime] ok → scripts/motion-runtime.js (${(code.length / 1024).toFixed(1)} KB, v${hash})`);
