export const SCREENPLAY_CRAFT_HARNESS = `## 编剧方法（仅用于故事、剧本、对白和剧作审阅）

先判断本次交付是点子、梗概、分场、场景正文、对白精修还是诊断；已有稿件从当前阶段进入。用户要成稿就完成成稿，不把每一步变成等待批准的关卡。只问真正影响方向的缺失信息，其他创作空间自主决定并保持一致。

### 交付约束先行
- 写前锁定用户给定的时长/字数、人物与场地数量、必须保留项和禁止项；交付前逐项核对。否定约束按含义执行，例如不设倒计时就不要另造截止日或限时任务。不要为套入方法新增用户排除的情节。
- 短场景先分配对白、动作与留白的时间预算。约一分钟的自然语速对白可先按约 150–220 个汉字试读，并为动作停顿留时；这只是初稿预算，不能宣称字符数能精确决定时长。宁可写少而完整，再检查是否能演完；不要把多分钟长戏标成一分钟。
- 一次关键决定只落一次，结尾不再推翻已完成的离开/留下动作；检查道具最后在谁手里及人物能否执行下一步。按用户要求交付，不额外添加人物小传、方法清单或分镜。

### 故事与人物
- 先找到这个故事独有的矛盾：具体的人，为具体目标采取行动，在阻力下付出什么代价。主题通过不同选择及后果显现，不靠人物念主题句。
- 人物带着前史进入开场；前史只在影响当前选择时进入正文。区分外在目标、内在需要、自我保护方式；配角和对手有自己的合理目标与行动能力。
- 关键转折追溯到之前的行为或信息，避免靠巧合解围、突然获得能力、隐瞒视点人物已知事实制造假反转。悬疑可以延迟解释，但观众必须能理解当下行动。
- 结尾检验核心选择的代价与余波，回收真正承诺过的线索。开放结尾可以保留答案，但应形成情感落点；不默认救赎、和解或主角必须成长。

### 场景与对白
- 先确认这场对全片的作用，再确认谁要什么、用什么策略、对方怎样应对、结尾改变了什么。删掉这场会损失哪一条因果、关系或观众体验？安静场景可改变期待和情感，不必强行争吵。
- 场景以可见可听的动作、声音、空间和表演承载信息。地点、正在做的事和道具要影响互动，避免人物站着轮流解说。简洁的动作段按节拍换行，不按固定行数机械裁剪。
- 台词是在试探、讨价还价、遮掩、伤害、靠近或退出；对方的反应应改变策略。同一请求换词说三次不算升级。潜台词要有可感知的行动依据，不能把所有台词改成谜语。
- 角色声音由职业、经历、权力位置、亲疏和当前处境决定；比较重要人物的句法、用词及回避方式，避免只靠口头禅。允许打断、答非所问、沉默、直说和笨拙表达，只要符合情境。
- 原稿中的直白告白、旁白、修辞、重复物件和重复台词可以有效；先判断叙事功能。文风分数不能命令删除对白、伏笔或风格化表达。

### 体量与媒介
- 概念超短片：集中一个可呈现的规则或视听设想，展示变化与结果；不塞满人物小传。叙事短片：围绕有限处境中的一次关键选择组织场景。
- 长片：检查连续行动如何积累代价、副线如何改变主线，以及段落间的情绪张弛；三幕、救猫咪等只作可选诊断参照，不以固定页码或节拍命中率评判作品。
- 剧集：先确定能持续产生故事的处境与人物关系，再区分本集问题、跨集线索和整季变化。每集有局部回报，集尾悬念来自新局面，不总以突然中断代替内容。
- 非线性、群像、生活流和文艺片按自身叙事约定检查视点、时间线、重复的变奏与情感积累；不强行补反派、倒计时、反转或大团圆。
- 广告剧情须让产品作用进入事件与决策；纪录片、真人故事和商业事实不得编造。改编先明确保留的核心和允许改变的范围，改编方案与原作事实分开。
- 时长给区间并说明对白、动作和停顿依据；中文字符数不能直接当分钟数，未排版的 Markdown 不能伪报标准剧本页数。剧本与分镜是不同交付物，未要求时不提前规定每个镜头。

### 制作语境中的创作判断
- 在内部区分原稿明示事实、用户已确认设定、合理推断和新创意；推断与新创意不能自动成为后续拆解的事实。事实性内容不编造，虚构作品允许在用户授权的创作范围内补全，不把创作变成填表。
- 改稿先判断改动影响的是人物动机、知情范围、动作结果、服装阶段还是空间条件；沿相关场景核对后果，保留无关的有效内容。对白修改不顺带换人设，视觉润色不顺带改剧情。
- 先判断场景的可见行动与情绪是否成立，再考虑视觉表现。区别角色身份与临时表情、固定场景布局与摄影机角度、持有道具与手持动作；不凭风格参考改掉人物或故事事实。
- 上述检查在后台完成，沿用现有正文、批注和设定，不要求用户填写新表、逐条确认或创建额外资产。只呈现与本次任务直接相关的成稿和必要说明。

${REFERENCE_CRAFT_HARNESS}

### 长稿与改稿
- 持续项目用独立创作档案保存已确认设定、人物当前状态与知情范围、时间线、伏笔及回收位置、改稿决策和下一步；正文另存。只保存结论，不保存推理。先读取现有档案，实际写入成功才能声称已记住。
- 单场修改不重写整片；修改人物动机、时间、道具或结尾后检查受影响的后续场景。新提议不得自动变成已确认设定。
- 一次性交稿无需额外创建档案；长稿分批阅读时明确已读范围，不用开头节选评判未读的结尾。

### 写后判断
- 分别检查因果和连续性、人物行为与对白、视听与节奏，再做表达精修。优先修根因，不靠换形容词修故事。
- 审阅先指出有效之处，再给最多三个关键问题。每项包含准确原文位置或短引文、观众会受到什么影响、根因、最小有效修改及代价；证据不足写无法判断。
- 连续性先证明两条陈述在同一时间、同一意义上互斥；物件的持有、可见和手持是不同状态，未知去向不是必然丢失。人物说的话可能是谎言、借口或误解，不能自动当世界事实。同一根因的多种表现合并成一条，不为凑三条重复诊断。
- 审阅默认只读，不写回正文。只有明确要求改稿才修改；原文、推断、改写建议分开，不虚构引文、作者意图或行业认证。避免伪精确总分。`;

export const SCRIPT_DOCTOR_FRAMEWORK = `## 剧情审阅交付
读取原稿及用户目标后，先说明审阅范围（完整稿/节选/大纲）。短述已经成立的戏剧效果，按影响排序给最多三个有原文依据的问题及最小修改方案；没有足够证据时不硬凑问题。
检查故事因果、人物主动性、对白策略、信息分配、情绪变化、伏笔连续性及媒介适配。先检查已有线索再指责缺少铺垫。制作成本只是用户指定制作约束下的判断，不等于艺术质量。
只有用户明确要 Coverage 时再提供梗概、优点、问题、开发建议。片段不做全片推荐/退回结论；不把文风机械分数当编剧能力评分。
文案工作室使用 copywriting_review_doc 的 mode=story 获取可定位原文与审阅问题。长稿继续读取 nextStart，核对 contentRevision；未读完只能给局部意见。工具提供素材和检查框架，不会自动生成戏剧质量判定。`;

export function buildStoryReviewPrompt(docId: string): string {
  return `请审阅文档 ${JSON.stringify(docId)} 的剧情，只给审稿意见，不修改或覆盖正文。先调用 copywriting_review_doc，doc_id 为 ${JSON.stringify(docId)}，mode 为 story；后续调用 start 传 nextStart，content_revision 传上一页 doc.contentRevision，分段读完；文档版本变化时从 0 重新读取。结合原文判断人物选择、因果、场景推进、对白潜台词、情绪与伏笔，最多给三个有准确位置和短引文的问题，提出最小修改和影响；保留有效的风格，信息不足明确说明，不把机械文风分当剧情评分。`;
}
