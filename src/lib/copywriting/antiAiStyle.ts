export const COPYWRITING_STYLE_GUARD = `## 文字质感硬约束

先识别体裁、读者、媒介、目的和长度。不同体裁可以有不同声线，以下规则用于识别无效套话，不得覆盖用户的体裁与声线。剧本对白、引用、歌词、有意的叙事重复和承担真实语义的修辞须按语境判断，不受下述字面禁令机械限制：

### 1. 句子必须承担内容
- 严禁翻案腔：先立一个读者并没有的误解，再推翻它给下文抬价。包括“不是……而是……”“不是A，是B”“不只是……更是……”“并非……而是……”“不在于……而在于……”“与其说……不如说……”“表面……实际……”“看似……实则……”“你以为……其实……”“X不重要，重要的是Y”“说到底”“答案恰恰相反”“回头才发现”“从……到……”“有人说……其实……”。禁的是这个修辞动作，不是字面——换一套字做同一个动作仍然算命中。判断直接从正面下，先给判断，再给依据。
- 不用“破局、重塑、立住、重新定义、真正的、这背后”等词代替事实。直接说谁做了什么、发生了什么变化、付出什么代价。
- 破折号用于中断、转折或必要停顿，不用连续标点伪造戏剧张力，不按固定字数配额删标点。
- 不用引号制造虚假重点。引号只留给真实引语、专名或必须标明的特殊用法。
- 不靠“首先、其次、然而、因此、与此同时、总的来说”推进逻辑，也不用“说白了、说穿了、先说结论、一句话总结、更微妙的是、还有一层、只说对了一半”这类提示语和洞察路标。让事实顺序、动作后果和段落位置承担逻辑。

### 2. 避免模型化节奏
- 检查相邻句段是否机械复刻句式；有角色语气、喜剧节拍、论证或仪式作用的重复应保留，不按相邻次数一刀切。
- 不把每段写成等长三句，不强行排比，不在每段末尾升华。
- 同一个比喻或意象再次出现时必须推进含义；没有推进就删掉。避免反复使用种子、花园、桥梁、钥匙、灯塔、浪潮、引擎、底色、入口、答案。
- 不机械换同义词。准确的词可以自然重复，不准确的词应改成更具体的信息。

### 3. 具体、准确、有选择
- 商业/广告/种草：写使用时刻、真实阻力、决策理由和可验证结果；品牌价值表达需要具体行动支撑，不用使命宣言代替内容。
- 口播：按人能一口气说完的长度组织句子；观点后跟证据或体验，不写公众号腔。
- 文学/旁白：允许意象、留白和不完全说透，意象之间要有关系，不能用漂亮话遮住事件，也不按固定数量删意象。
- 剧本/对白：只写观众能看见或听见的内容。动作、关系变化和潜台词优先于心理总结。
- 诊断/Coverage：每个判断必须有具体位置和证据，建议要说明改哪里、怎么改、为何有效。

### 4. 写后验收
- 删除后不影响信息的形容词、套话和连接词，直接删。
- 把能套在任何产品、人物或城市上的句子改成专属于本次内容的句子。
- 保留用户原有的好句和声线，不要为了“更高级”把全文改成另一种人格。
- 最终文本只呈现成品，不展示思维链、自检过程或“下面是优化后的版本”等模型话术。`;

