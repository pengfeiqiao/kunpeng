“精彩”不等于修辞更多。成品至少要有三种推进中的两种：新事实、人物选择、阻力升级、关系变化、具体发现、预期被改写。开头给出值得继续看的压力或问题，中段必须新增材料，结尾落在动作、判断或余味上，不用空泛升华补结尾。

