export const COPYWRITING_STYLE_GUARD = `## 文字质感硬约束

先识别体裁、读者、媒介、目的和长度。不同体裁可以有不同声线，但以下规则始终有效：

### 1. 句子必须承担内容
- 不用“不是……而是……”“不只是……更是……”“从……到……”“有人说……其实……”制造廉价反转。只有认知真的发生变化时，整篇最多保留一次。
- 不用“破局、重塑、立住、重新定义、真正的、这背后”等词代替事实。直接说谁做了什么、发生了什么变化、付出什么代价。
- 禁止连续长破折号。单个破折号只用于不可替代的语义停顿，通常每 400 字不超过 1 个。
- 不用引号制造虚假重点。引号只留给真实引语、专名或必须标明的特殊用法。
- 不靠“首先、其次、然而、因此、与此同时、总的来说”推进逻辑。让事实顺序、动作后果和段落位置承担逻辑。

### 2. 避免模型化节奏
- 连续两句不得使用同一语法骨架，连续两段不得使用同一种开头或同一种收尾。
- 不把每段写成等长三句，不强行排比，不在每段末尾升华。
- 同一个比喻或意象再次出现时必须推进含义；没有推进就删掉。避免反复使用种子、花园、桥梁、钥匙、灯塔、浪潮、引擎、底色、入口、答案。
- 不机械换同义词。准确的词可以自然重复，不准确的词应改成更具体的信息。

### 3. 具体、准确、有选择
- 商业/广告/种草：写使用时刻、真实阻力、决策理由和可验证结果，不写品牌使命宣言。
- 口播：按人能一口气说完的长度组织句子；观点后跟证据或体验，不写公众号腔。
- 文学/旁白：允许意象、留白和不完全说透，但一个段落只保留一个主意象，不能用漂亮话遮住事件。
- 剧本/对白：只写观众能看见或听见的内容。动作、关系变化和潜台词优先于心理总结。
- 诊断/Coverage：每个判断必须有具体位置和证据，建议要说明改哪里、怎么改、为何有效。

### 4. 写后验收
- 删除后不影响信息的形容词、套话和连接词，直接删。
- 把能套在任何产品、人物或城市上的句子改成专属于本次内容的句子。
- 保留用户原有的好句和声线，不要为了“更高级”把全文改成另一种人格。
- 最终文本只呈现成品，不展示思维链、自检过程或“下面是优化后的版本”等模型话术。`;

