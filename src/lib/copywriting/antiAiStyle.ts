export function buildCopywritingTaskHarness(task: string): string {
  const signal = task.toLowerCase();
  const wantsPrompt = /提示词|prompt|生图|图生图|文生图|生视频|视频生成|mg\s*动画|seedance|seedream|omni|分镜提示/.test(signal);
  const wantsDiagnosis = /剧本医生|剧本诊断|剧本分析|coverage|审剧本|评估剧本|结构诊断/.test(signal);
  const wantsScreenplay = wantsDiagnosis || /剧本|对白|台词|场景|分场|人物弧线|短片脚本|电影|悬念|潜台词/.test(signal);
  const wantsAdvertising = /广告|品牌|种草|tvc|campaign|投放|转化|卖点|商业片/.test(signal);
  const sections = [COPYWRITING_STYLE_GUARD, COPYWRITING_CRAFT_HARNESS];

  if (wantsPrompt) sections.push(PROMPT_AUTHORING_HARNESS);
  if (wantsScreenplay) sections.push(SCREENPLAY_CRAFT_HARNESS);
  if (wantsAdvertising) sections.push(AD_DIRECTOR_FRAMEWORK);
  if (wantsDiagnosis) sections.push(SCRIPT_DOCTOR_FRAMEWORK);

  return sections.join('\n\n');
}

export function withCopywritingStyleGuard(task: string): string {
  return `${task.trim()}

请同时遵守以下写作质感规则：
${buildCopywritingTaskHarness(task)}`;
}

export function buildGuidePrompt(kind: 'ad' | 'scriptDoctor' | 'videoScript'): string {
  if (kind === 'ad') {
    return withCopywritingStyleGuard(`请按“广告导演”的方法，为品牌策划一条短视频广告，目标投放抖音。
先输出创意策略，不要直接写一篇漂亮但通用的广告稿。需要包含：人群洞察、核心冲突、前三秒钩子、完播结构、转发动机、1-2 个可执行创意方向。`);
  }
  if (kind === 'scriptDoctor') {
    return withCopywritingStyleGuard(`请按“剧本医生”的 Coverage 方法分析诊断以下剧本。
先做结构解析，再按结构、角色、对话、情感、视觉叙事、制作可行性给出诊断。每个问题都要有具体证据和修改建议。`);
  }
  return withCopywritingStyleGuard(`请写一个视频脚本。
如果是文学类、旅行类、旁白类脚本，保留意象、留白和节奏；如果是口播类脚本，保持真人说话感；不要写成通用宣传片文案。`);
}
