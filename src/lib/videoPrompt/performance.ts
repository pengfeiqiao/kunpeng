/** 返回文本中命中的 AI 短剧/漫剧风词汇；无命中返回空数组 */
export function findAiDramaPerformanceHits(text?: string): string[] {
  if (!text) return [];
  return AI_DRAMA_BAN_TERMS.filter((term) => text.includes(term));
}
